# coding: utf-8
"""Gate: the shard surface must be an inventory, and must never look implemented.

The failure this file exists to prevent is a stub that behaves. A stub that
returns a plausible value is worse than no file at all: the next developer
imports it, gets silence, and ships a decision built on nothing. So the controls
here are mostly negative -- change one thing in a stub and assert the check
refuses it -- plus a real-atlas run, because a gate that only ever sees fixtures
has never met the tree it describes.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

ELIZA = Path(__file__).resolve().parents[1]
TOOL = ELIZA / "tools" / "shard_intake.py"
#: Tracked sibling of `eliza/`, which is generated by tools/publicize.py.
SHARDS = ELIZA / "shards"


def _load():
    spec = importlib.util.spec_from_file_location("shard_intake_under_test", TOOL)
    assert spec and spec.loader, "shard_intake.py could not be loaded from %s" % TOOL
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


intake = _load()
ATLAS = intake.DEFAULT_ATLAS

needs_atlas = pytest.mark.skipif(
    not ATLAS.is_file(),
    reason="the Kali atlas is not on this host (%s); the surface cannot be checked "
           "against the tree it describes" % ATLAS)


def test_an_absent_census_is_exit_2_not_drift(tmp_path, capsys):
    """The control for the third state, and the reason it exists.

    The atlas lives outside the repo, so a host that never ran the Kali census
    cannot judge this surface. That used to arrive as ``SystemExit`` -- exit 1,
    byte-identical to "the stubs disagree with the atlas" -- and the commit gate
    would have refused a healthy tree for a reason that was about the host. Exit 2
    means COULD NOT PERFORM THE RUN, and it has to stay distinguishable from the
    drift exit for the tier stanza to tell the reader which one happened.
    """
    absent = tmp_path / "no_atlas_here.json"
    assert intake.main(["--atlas", str(absent), "--check"]) == 2
    assert "CANNOT JUDGE" in capsys.readouterr().err


def test_an_unreadable_census_is_also_exit_2(tmp_path):
    """Corrupt input is a missing judgement, not a drifted surface."""
    broken = tmp_path / "atlas.json"
    broken.write_text("{not json", encoding="utf-8")
    assert intake.main(["--atlas", str(broken), "--check"]) == 2


@needs_atlas
def test_the_surface_is_clean_against_the_real_atlas():
    ok, problems, counts = intake.check(intake.read_atlas(ATLAS))
    assert ok, "\n".join(problems[:5])
    assert counts["shards"] > 1000, counts


@needs_atlas
def test_every_unit_in_the_atlas_has_a_stub():
    atlas = intake.read_atlas(ATLAS)
    entries = intake.units(atlas)
    indexed = {entry["shard_id"] for entry in
               json.loads(intake.INDEX.read_text(encoding="utf-8"))["shards"]}
    assert {entry["shard_id"] for entry in entries} == indexed
    for entry in entries[:50]:
        assert (intake.REPO / entry["path"]).is_file(), entry["path"]


@needs_atlas
def test_every_class_the_atlas_counts_is_reachable_through_a_shard():
    """The atlas names at most six classes per module; the rest must not vanish.

    Without this, the surface silently describes itself as complete while 143
    classes sit behind 52 module boundaries with no address, and the counter a
    reader trusts (the shard total) cannot reveal it.
    """
    atlas = intake.read_atlas(ATLAS)
    entries = intake.units(atlas)
    named = sum(1 for entry in entries if entry["kind"] == "class")
    residual = sum(entry["unnamed"] for entry in entries if entry["kind"] == "module")
    declared = sum(int(module.get("classes") or 0)
                   for module in (atlas.get("modules") or {}).values())
    assert named + residual == declared, (named, residual, declared)


@needs_atlas
def test_a_residual_shard_names_its_count_instead_of_inventing_a_class():
    entries = intake.units(intake.read_atlas(ATLAS))
    residual = [entry for entry in entries if entry["kind"] == "module"]
    assert residual, "the atlas has truncated class lists; residuals must exist"
    for entry in residual:
        assert entry["class"] is None, entry
        assert entry["unnamed"] > 0, entry
    text = (intake.REPO / residual[0]["path"]).read_text(encoding="utf-8")
    assert "CLASS_NAME = None" in text
    assert "UNNAMED_CLASSES = " in text


@needs_atlas
def test_no_two_shards_share_a_path_on_a_case_insensitive_disk():
    """Kali carries both SCRIPTS/ and scripts/; Windows collapses them."""
    paths = [entry["path"].lower() for entry in intake.units(intake.read_atlas(ATLAS))]
    assert len(paths) == len(set(paths)), "two shards would be written to one file"


