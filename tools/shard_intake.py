#!/usr/bin/env python3
# coding: utf-8
"""Stub the Kali codebase into ELIZA as an optional, adoptable shard surface.

`atlas_kali-linux.json` enumerates what the Kali lane actually holds: 18 trees,
679 modules, and the named class units inside them. That inventory is the shard
set -- one shard per unit, 1,131 of them -- and this tool writes one stub module
per shard plus an index, so a forward developer can pick a unit up deliberately
instead of copying from a tree they cannot see.

**A stub is not an implementation, and this tool refuses to write one that looks
like one.** Every stub carries its provenance (Kali module, class, atlas date),
`WIRED = False`, and a `load()` that raises with the reason. Nothing imports a
stub to get behaviour, because nothing in it behaves. The point of the surface is
that the *decision* to adopt is explicit: you see the unit, you see where it came
from, and wiring it is a reviewable change rather than a hopeful import.

  python tools/shard_intake.py --list                 # the shard set, by tree
  python tools/shard_intake.py --list --tree CORE
  python tools/shard_intake.py --write                # regenerate stubs + index
  python tools/shard_intake.py --check                # the gate: exit 1 on drift
  python tools/shard_intake.py --adopt "kali:CORE/paths.py#Paths"

Why generated rather than copied: a copied module drags its imports, its globals
and its licence into a package that advertises none of them. A generated stub
drags nothing, and `--check` can prove the surface still matches the atlas.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

REPO = Path(__file__).resolve().parents[1]          # Project_ELIZA/
DEFAULT_ATLAS = Path.home() / "yggdrasil_forest" / "atlas_kali-linux.json"
#: A tracked sibling of `eliza/`, not a subdirectory of it. `eliza/` is GENERATED by
#: `tools/publicize.py` from PUBLIC_MANIFEST.json, and `--clean` deletes what it
#: generated -- 1,131 stubs written there would survive until the next
#: materialise and then vanish, which is the exact shape of the defect this
#: estate keeps recording. Authored content goes where authored content lives.
SHARDS = REPO / "shards"
INDEX = SHARDS / "SHARD_INDEX.json"
#: The adoption ledger: the only file here a human writes, and the only place a
#: shard may stop being a stub. A wired shard names the test that proves it, so
#: "wired" is a claim with a control rather than a flipped boolean.
WIRED = SHARDS / "WIRED.json"
SCHEMA = "eliza.shard-intake/1"

STUB = '''# coding: utf-8
"""{tree} / {module} :: {klass} -- INTAKE STUB. Not an implementation.

Source: kali-linux {source} (class {klass}, {lines} lines in the module,
{public_api} public API entries)
Atlas:  atlas_kali-linux.json, generated {generated}
Adopt:  python tools/shard_intake.py --adopt "{shard_id}"

This file exists so the unit is *visible and addressable* from ELIZA. It has no
behaviour: `load()` raises. Wiring it is a deliberate change, made against the
tutorial in docs/TUTORIAL_SHARD_DEV_2026-11-02.md, and the first step is to read
the Kali source rather than to import this module.
"""
from __future__ import annotations

WIRED = False
SHARD_ID = "{shard_id}"
SOURCE_ENVIRONMENT = "kali-linux"
SOURCE_MODULE = "{module}"
CLASS_NAME = "{klass}"
TREE = "{tree}"


def describe() -> dict:
    """What this shard is, where it came from, and whether it runs."""
    return {{
        "shard_id": SHARD_ID,
        "tree": TREE,
        "source_module": SOURCE_MODULE,
        "class_name": CLASS_NAME,
        "environment": SOURCE_ENVIRONMENT,
        "wired": WIRED,
    }}


def load(*args, **kwargs):
    """Refuse, loudly, with the reason and the place to start reading."""
    raise NotImplementedError(
        "shard %s is an intake stub: %s is not implemented in ELIZA. "
        "Read the Kali source at %s, then see "
        "docs/TUTORIAL_SHARD_DEV_2026-11-02.md" % (SHARD_ID, CLASS_NAME, SOURCE_MODULE)
    )
'''


def slug(text: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    if not cleaned:
        cleaned = "unit"
    if cleaned[0].isdigit():
        cleaned = "s_" + cleaned
    return cleaned


#: What the index records. The comparison in `check()` uses exactly these, so an
#: extractor field the index does not carry cannot manufacture a false defect.
INDEX_KEYS = ("shard_id", "tree", "module", "class", "lines", "public_api", "path")


def read_atlas(path: Path) -> Dict:
    if not path.is_file():
        raise SystemExit("atlas not found: %s\n"
                         "Pass --atlas, or run tools/domain_trees.py on the Kali lane."
                         % path)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit("%s is not valid JSON: %s" % (path, exc))


def units(atlas: Dict) -> List[Dict]:
    """One entry per named class unit in the atlas, sorted for a stable diff."""
    modules = atlas.get("modules") or {}
    generated = str(atlas.get("generated_at", ""))[:10]
    out: List[Dict] = []
    for module_name in sorted(modules):
        meta = modules[module_name] or {}
        tree = str(meta.get("tree") or "(root)")
        for klass in sorted(meta.get("top_classes") or []):
            shard_id = "kali:%s#%s" % (module_name, klass)
            out.append({
                "shard_id": shard_id,
                "tree": tree,
                "module": module_name,
                "class": klass,
                "lines": int(meta.get("lines") or 0),
                "public_api": int(meta.get("public_api") or 0),
                "path": "shards/%s/%s__%s.py"
                        % (slug(tree), slug(module_name.replace("/", "_").replace(".py", "")),
                           slug(klass)),
            })
    # Kali carries both `SCRIPTS/` and `scripts/`, and Windows cannot hold both:
    # the first version of this tool wrote 1,131 shards and left 1,118 files, with
    # the lowercase tree silently overwriting the uppercase one. A collision gets
    # a content-addressed suffix instead of a shrug, and the count stays honest.
    seen = set()
    for entry in out:
        entry["generated"] = generated
        if entry["path"].lower() in seen:
            digest = hashlib.sha1(entry["shard_id"].encode("utf-8")).hexdigest()[:8]
            entry["path"] = entry["path"][:-3] + "__%s.py" % digest
        seen.add(entry["path"].lower())
    return out


def render_index(entries: Sequence[Dict], atlas: Dict) -> str:
    payload = {
        "schema": SCHEMA,
        "note": ("Generated by Project_ELIZA/tools/shard_intake.py from the Kali atlas. "
                 "Every entry is a stub: WIRED = False. Regenerate, never hand-edit."),
        "atlas": {
            "environment": "kali-linux",
            "generated_at": atlas.get("generated_at"),
            "root": atlas.get("root"),
            "trees": (atlas.get("totals") or {}).get("trees"),
        },
        "counts": {
            "shards": len(entries),
            "modules": len({entry["module"] for entry in entries}),
            "trees": sorted({entry["tree"] for entry in entries}),
        },
        "shards": [{key: entry[key] for key in INDEX_KEYS} for entry in entries],
    }
    return json.dumps(payload, indent=1, sort_keys=False) + "\n"


def write(entries: Sequence[Dict], atlas: Dict) -> Dict:
    written = 0
    trees = {entry["tree"] for entry in entries}
    # Tree directories are generated wholesale: a shard that left the atlas must
    # not survive as an orphan file a reader can import.
    if SHARDS.exists():
        for child in SHARDS.iterdir():
            if child.is_dir():
                shutil.rmtree(child)
    for tree in trees:
        directory = SHARDS / slug(tree)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "__init__.py").write_text(
            '"""Intake stubs for the %s tree. Generated; see SHARD_INDEX.json."""\n'
            % tree, encoding="utf-8", newline="\n")
    for entry in entries:
        path = REPO / entry["path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        text = STUB.format(tree=entry["tree"], module=entry["module"],
                           klass=entry["class"], source=entry["module"],
                           lines=entry["lines"], public_api=entry["public_api"],
                           generated=entry["generated"], shard_id=entry["shard_id"])
        path.write_text(text, encoding="utf-8", newline="\n")
        written += 1
    INDEX.write_text(render_index(entries, atlas), encoding="utf-8", newline="\n")
    if not WIRED.is_file():
        # Written once and never regenerated: this is the adoption ledger, and a
        # --write that reset it would quietly un-adopt work that is in production.
        WIRED.write_text(json.dumps({
            "schema": SCHEMA,
            "note": ("Shard id -> {test, commit}. A shard listed here has been wired "
                     "into ELIZA behind its stub path; the test is the evidence. "
                     "Edit by hand, in the adopting commit."),
            "wired": {},
        }, indent=1) + "\n", encoding="utf-8", newline="\n")
    return {"written": written, "trees": len(trees), "index": str(INDEX)}


def wired_registry() -> Dict[str, Dict]:
    """Shard id -> {test, commit} for every shard a human has adopted."""
    if not WIRED.is_file():
        return {}
    try:
        data = json.loads(WIRED.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit("%s is not valid JSON: %s" % (WIRED.name, exc))
    return data.get("wired") or {}


def _stub_problems(path: Path, entry: Dict, wired: Optional[Dict] = None) -> List[str]:
    problems: List[str] = []
    try:
        text = path.read_text(encoding="utf-8")
        tree = ast.parse(text)
    except (OSError, SyntaxError) as exc:
        return ["%s does not parse: %s" % (entry["path"], exc)]
    flags = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and isinstance(node.value, ast.Constant):
                flags[target.id] = node.value.value
    if wired:
        # Adopted: the flag flips, and the refusual is no longer expected here.
        if flags.get("WIRED") is not True:
            problems.append("%s is listed as wired in WIRED.json but declares "
                            "WIRED = %r" % (entry["path"], flags.get("WIRED")))
    elif flags.get("WIRED") is not False:
        problems.append("%s does not declare WIRED = False" % entry["path"])
    if flags.get("SHARD_ID") != entry["shard_id"]:
        problems.append("%s declares SHARD_ID %r, index says %r"
                        % (entry["path"], flags.get("SHARD_ID"), entry["shard_id"]))
    if flags.get("CLASS_NAME") != entry["class"]:
        problems.append("%s declares CLASS_NAME %r, index says %r"
                        % (entry["path"], flags.get("CLASS_NAME"), entry["class"]))
    loader = [node for node in tree.body
              if isinstance(node, ast.FunctionDef) and node.name == "load"]
    if not loader:
        problems.append("%s has no load() to refuse with" % entry["path"])
    elif not wired and not any(isinstance(node, ast.Raise)
                               for node in ast.walk(loader[0])):
        problems.append("%s load() does not raise: a stub that returns is a fake"
                        % entry["path"])
    imports = [node for node in ast.walk(tree)
               if isinstance(node, (ast.Import, ast.ImportFrom))]
    for node in imports:
        names = [alias.name for alias in node.names] if isinstance(node, ast.Import) \
            else [node.module or ""]
        for name in names:
            if name.split(".")[0] not in ("", "__future__"):
                problems.append("%s imports %r: a stub drags no dependencies"
                                % (entry["path"], name))
    return problems


def check(atlas: Dict) -> Tuple[bool, List[str], Dict]:
    problems: List[str] = []
    assigned = wired_registry()
    if not INDEX.is_file():
        return False, ["%s is absent; run --write" % INDEX.relative_to(REPO)], {}
    index = json.loads(INDEX.read_text(encoding="utf-8"))
    on_disk = {entry["path"]: {key: entry.get(key) for key in INDEX_KEYS}
               for entry in index.get("shards", [])}
    expected = {entry["path"]: {key: entry[key] for key in INDEX_KEYS}
                for entry in units(atlas)}
    for path in sorted(set(expected) - set(on_disk)):
        problems.append("%s is in the atlas but not the index" % path)
    for path in sorted(set(on_disk) - set(expected)):
        problems.append("%s is in the index but not the atlas (stale stub)" % path)
    for path in sorted(set(on_disk) & set(expected)):
        if on_disk[path] != expected[path]:
            problems.append("%s disagrees with the atlas: index %r, atlas %r"
                            % (path, on_disk[path], expected[path]))
    for entry in index.get("shards", []):
        file_path = REPO / entry["path"]
        if not file_path.is_file():
            problems.append("%s is indexed but absent" % entry["path"])
            continue
        problems.extend(_stub_problems(file_path, entry,
                                       assigned.get(entry["shard_id"])))
    for shard_id, claim in sorted(assigned.items()):
        if shard_id not in expected:
            problems.append("WIRED.json names %r, which is not in the atlas" % shard_id)
            continue
        test = claim.get("test") if isinstance(claim, dict) else None
        if not isinstance(test, str) or not test.strip():
            problems.append("WIRED.json entry %r names no test: a wired shard is a "
                            "claim, and a claim needs a control" % shard_id)
        elif not (REPO / test).is_file():
            problems.append("WIRED.json entry %r names %r, which does not exist"
                            % (shard_id, test))
    stray = [p for p in SHARDS.rglob("*.py")
             if p.name != "__init__.py"
             and str(p.relative_to(REPO)).replace("\\", "/") not in expected]
    for path in sorted(stray):
        problems.append("%s is not in the atlas: an adopted shard must be wired "
                        "deliberately, not left as a generated file"
                        % path.relative_to(REPO))
    counts = index.get("counts", {})
    if counts.get("shards") != len(expected):
        problems.append("index claims %r shards; the atlas yields %d"
                        % (counts.get("shards"), len(expected)))
    return (not problems), problems, {"shards": len(expected),
                                      "modules": len({e["module"] for e in expected.values()}),
                                      "trees": len({e["tree"] for e in expected.values()}),
                                      "wired": len(assigned)}


def adopt(shard_id: str, atlas: Dict) -> int:
    entries = {entry["shard_id"]: entry for entry in units(atlas)}
    entry = entries.get(shard_id)
    if entry is None:
        close = [key for key in entries if shard_id.lower() in key.lower()][:5]
        print("no shard %r in the atlas" % shard_id, file=sys.stderr)
        if close:
            print("closest: " + ", ".join(close), file=sys.stderr)
        return 1
    print("Adopt plan for %s" % shard_id)
    print("  source   kali-linux %s (class %s)" % (entry["module"], entry["class"]))
    print("  stub     %s" % entry["path"])
    print("  steps")
    print("    1. read the Kali source; list its imports and its side effects")
    print("    2. write a test in Project_ELIZA/tests/ that fails for the right reason")
    print("    3. implement behind the same module path and set WIRED = True")
    print("    4. add the shard id to shards/WIRED.json: {\"test\": <path>, "
          "\"commit\": <sha>}")
    print("    5. python tools/shard_intake.py --check   (stub drift, then wired drift)")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--atlas", default=str(DEFAULT_ATLAS))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--tree", help="limit --list to one tree")
    parser.add_argument("--adopt", metavar="SHARD_ID")
    args = parser.parse_args(argv)

    atlas = read_atlas(Path(args.atlas))
    entries = units(atlas)

    if args.write:
        result = write(entries, atlas)
        print("wrote %(written)d stub(s) across %(trees)d tree(s); index %(index)s"
              % result)
        return 0
    if args.check:
        ok, problems, counts = check(atlas)
        for problem in problems:
            print("DEFECT: " + problem)
        print("%s -- %d shard(s), %d module(s) yielding units, %d tree(s), %d wired"
              % ("clean" if ok else "%d defect(s)" % len(problems),
                 counts.get("shards", 0), counts.get("modules", 0),
                 counts.get("trees", 0), counts.get("wired", 0)))
        return 0 if ok else 1
    if args.adopt:
        return adopt(args.adopt, atlas)
    grouped: Dict[str, int] = {}
    for entry in entries:
        grouped[entry["tree"]] = grouped.get(entry["tree"], 0) + 1
    for tree in sorted(grouped):
        if args.tree and tree != args.tree:
            continue
        print("%-24s %4d shard(s)" % (tree, grouped[tree]))
    print("%-24s %4d" % ("total", len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
