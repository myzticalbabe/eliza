# coding: utf-8
"""The Kali shard surface: addressable, adoptable, and deliberately inert.

ELIZA ships 1,131 intake stubs, one per named class unit in the Kali lane's
atlas (`atlas_kali-linux.json`: 679 modules, 18 trees). Each stub is a *name with
provenance*, not an implementation -- `WIRED = False` and a `load()` that raises.
The surface exists so a forward developer can see what is available, choose a
unit, and wire it as a reviewable change instead of copying from a tree they
cannot inspect.

Read it as an inventory, never as a dependency:

    import shards
    len(shards.index())                        # 1131
    shards.trees()["CORE"]                     # how many units CORE offers
    shards.describe("kali:CORE/paths.py#Paths")  # provenance, and wired: False
    shards.load("kali:CORE/paths.py#Paths")      # NotImplementedError, with why

The index is generated by `Project_ELIZA/tools/shard_intake.py`; `--check` proves
the stubs still match the atlas and that none of them pretends to work.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

SHARDS_DIR = Path(__file__).resolve().parent
INDEX = SHARDS_DIR / "SHARD_INDEX.json"
#: Project root. The surface is a tracked sibling of `eliza/` (which is generated
#: by tools/publicize.py), so index paths are `shards/<tree>/<file>.py`.
REPO = SHARDS_DIR.parent


class ShardError(LookupError):
    """A shard that is not in the index, or a stub that is not on disk."""


def index() -> List[Dict]:
    """Every shard, in atlas order. Read-only: hand-editing it is a gate failure."""
    if not INDEX.is_file():
        raise ShardError("SHARD_INDEX.json is absent; run "
                         "python tools/shard_intake.py --write")
    return json.loads(INDEX.read_text(encoding="utf-8"))["shards"]


def trees() -> Dict[str, int]:
    """Shards per tree, because 'what is available' is a question about trees."""
    counts: Dict[str, int] = {}
    for entry in index():
        counts[entry["tree"]] = counts.get(entry["tree"], 0) + 1
    return dict(sorted(counts.items()))


def find(shard_id: str) -> Optional[Dict]:
    for entry in index():
        if entry["shard_id"] == shard_id:
            return entry
    return None


def _module_path(entry: Dict) -> Path:
    return REPO / entry["path"]


def load(shard_id: str):
    """Import one stub module -- to read its metadata, never to get behaviour.

    Importing by path rather than by package name keeps the surface usable from a
    checkout that has not been installed, which is how it is read in practice.
    """
    entry = find(shard_id)
    if entry is None:
        raise ShardError("no shard %r in the index (%d present)"
                         % (shard_id, len(index())))
    path = _module_path(entry)
    if not path.is_file():
        raise ShardError("%s is indexed but absent; run "
                         "python tools/shard_intake.py --write" % entry["path"])
    name = "eliza.shards._stub_" + str(abs(hash(shard_id)))
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ShardError("%s could not be loaded as a module" % entry["path"])
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def describe(shard_id: str) -> Dict:
    """What the shard is and where it came from -- without importing it."""
    entry = find(shard_id)
    if entry is None:
        raise ShardError("no shard %r in the index" % shard_id)
    described = {key: entry[key] for key in
                 ("shard_id", "tree", "module", "class", "path")}
    described["wired"] = False
    described["source_environment"] = "kali-linux"
    return described


def unwired(entries: Sequence[Dict] = ()) -> List[str]:
    """Shard ids that are still stubs. Every one of them, until someone wires it."""
    return [entry["shard_id"] for entry in (entries or index())]
